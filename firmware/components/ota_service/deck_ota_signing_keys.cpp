bool deck_ota_signing_public_key(
    uint32_t key_id,
    const uint8_t **sec1,
    size_t *sec1_size
)
{
    if (key_id != 1 || sec1 == nullptr || sec1_size == nullptr) {
        return false;
    }
    *sec1 = kSigningKeyV1;
    *sec1_size = sizeof(kSigningKeyV1);
    return true;
}
